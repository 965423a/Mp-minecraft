def gb_code(ch: str) -> int:
    b = ch.encode("gb2312")
    return (b[0] << 8) | b[1]

out = bytearray()
items = [(p, [c for c in chars if c]) for p, chars in TABLE]
out += struct.pack("<H", len(items))
for pinyin, chars in items:
    assert len(pinyin) <= 255
    assert len(chars) <= 255
    out.append(len(pinyin))
    out += pinyin.encode("ascii")
    out.append(len(chars))
    for c in chars:
        out += struct.pack("<H", gb_code(c))

path = sys.argv[1] if len(sys.argv) > 1 else "boot/data/pinyin_pack.bin"
with open(path, "wb") as f:
    f.write(out)
total_chars = sum(len(chars) for _, chars in items)
print(f"wrote {path}: {len(items)} pinyin entries, {total_chars} chars, {len(out)} bytes")
